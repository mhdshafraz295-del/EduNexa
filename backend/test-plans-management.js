/**
 * Automated Verification Test Suite for EduNexa SaaS - Step 2: Dynamic Subscription Plan Management
 */
const BASE_URL = 'http://localhost:5000/api';

async function runStep2Tests() {
  console.log('🧪 Starting EduNexa SaaS Step 2: Plans Management Verification Tests...\n');
  let superAdminToken = '';
  let instituteAdminToken = '';
  let createdPlanId = null;
  let duplicatedPlanId = null;

  // Test 1: Super Admin Login
  console.log('Test 1: SUPER_ADMIN Login...');
  const saRes = await fetch(`${BASE_URL}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'superadmin@edunexa.com', password: 'SuperAdmin123!' }),
  });
  const saData = await saRes.json();
  if (!saData.success || !saData.token || saData.user.role !== 'SUPER_ADMIN') {
    throw new Error(`Super Admin login failed: ${JSON.stringify(saData)}`);
  }
  superAdminToken = saData.token;
  console.log('  ✅ Passed: SUPER_ADMIN authenticated successfully.');

  // Test 2: Institute Admin Login
  console.log('Test 2: Institute Admin Login...');
  const iaRes = await fetch(`${BASE_URL}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'admin@edunexa.com', password: 'Admin123!' }),
  });
  const iaData = await iaRes.json();
  if (!iaData.success || !iaData.token || iaData.user.role !== 'ADMIN') {
    throw new Error(`Institute Admin login failed: ${JSON.stringify(iaData)}`);
  }
  instituteAdminToken = iaData.token;
  console.log('  ✅ Passed: Institute Admin authenticated successfully.');

  // Test 3: Fetch Feature Catalog (SUPER_ADMIN)
  console.log('Test 3: Fetch Feature Catalog (GET /api/super-admin/features)...');
  const featRes = await fetch(`${BASE_URL}/super-admin/features`, {
    headers: { Authorization: `Bearer ${superAdminToken}` },
  });
  const featData = await featRes.json();
  if (!featData.success || !featData.data.length || !featData.grouped.Academic) {
    throw new Error(`Failed to fetch features: ${JSON.stringify(featData)}`);
  }
  console.log(`  ✅ Passed: Retrieved ${featData.data.length} catalog features grouped by categories.`);
  const allFeatureIds = featData.data.map(f => f.id);
  const halfFeatureIds = allFeatureIds.slice(0, 5);

  // Test 4: Create a New Dynamic Plan with Limits & Features
  console.log('Test 4: Create a Dynamic Custom Plan (POST /api/super-admin/plans)...');
  const planPayload = {
    name: 'Automation Test Tier',
    description: 'Custom plan generated by automated test suite',
    price: 3500.00,
    currency: 'LKR',
    duration: 3,
    durationType: 'MONTHS',
    isActive: true,
    isPopular: false,
    displayOrder: 10,
    studentLimit: 250,
    teacherLimit: 20,
    adminLimit: 3,
    classLimit: 15,
    courseLimit: 10,
    storageLimitGb: 15,
    branchLimit: 1,
    featureIds: halfFeatureIds,
  };

  const createRes = await fetch(`${BASE_URL}/super-admin/plans`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${superAdminToken}`,
    },
    body: JSON.stringify(planPayload),
  });
  const createData = await createRes.json();
  if (!createData.success || !createData.data.id) {
    throw new Error(`Failed to create plan: ${JSON.stringify(createData)}`);
  }
  createdPlanId = createData.data.id;
  const enabledCount = createData.data.features.filter(f => f.isEnabled).length;
  console.log(`  ✅ Passed: Created Plan '${createData.data.name}' (ID: ${createdPlanId}) with ${enabledCount} enabled features.`);

  // Test 5: Edit Price, Duration, and Limits (PUT /api/super-admin/plans/:id)
  console.log('Test 5: Update Price, Duration, and Limits (PUT /api/super-admin/plans/:id)...');
  const updatePayload = {
    ...planPayload,
    name: 'Automation Test Tier Updated',
    price: 4200.00,
    duration: 6,
    studentLimit: 400,
    teacherLimit: 35,
    isPopular: true,
  };

  const updateRes = await fetch(`${BASE_URL}/super-admin/plans/${createdPlanId}`, {
    method: 'PUT',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${superAdminToken}`,
    },
    body: JSON.stringify(updatePayload),
  });
  const updateData = await updateRes.json();
  if (!updateData.success || updateData.data.price !== 4200 || updateData.data.studentLimit !== 400 || updateData.data.duration !== 6) {
    throw new Error(`Failed to update plan: ${JSON.stringify(updateData)}`);
  }
  console.log(`  ✅ Passed: Plan updated to Price: LKR 4,200.00, Duration: 6 MONTHS, Student Limit: 400.`);

  // Test 6: Duplicate Plan (POST /api/super-admin/plans/:id/duplicate)
  console.log('Test 6: Duplicate Plan (POST /api/super-admin/plans/:id/duplicate)...');
  const dupRes = await fetch(`${BASE_URL}/super-admin/plans/${createdPlanId}/duplicate`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${superAdminToken}` },
  });
  const dupData = await dupRes.json();
  if (!dupData.success || !dupData.data.name.includes('(Copy)')) {
    throw new Error(`Failed to duplicate plan: ${JSON.stringify(dupData)}`);
  }
  duplicatedPlanId = dupData.data.id;
  console.log(`  ✅ Passed: Successfully cloned plan as '${dupData.data.name}' (ID: ${duplicatedPlanId}). Default isActive is ${dupData.data.isActive}.`);

  // Test 7: Toggle Plan Active / Inactive Status
  console.log('Test 7: Deactivate Plan (PATCH /api/super-admin/plans/:id/status)...');
  const statusRes = await fetch(`${BASE_URL}/super-admin/plans/${createdPlanId}/status`, {
    method: 'PATCH',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${superAdminToken}`,
    },
    body: JSON.stringify({ isActive: false }),
  });
  const statusData = await statusRes.json();
  if (!statusData.success || statusData.data.isActive !== false) {
    throw new Error(`Failed to deactivate plan: ${JSON.stringify(statusData)}`);
  }
  console.log(`  ✅ Passed: Plan ID ${createdPlanId} status updated to Inactive.`);

  // Test 8: Verify Public Active Plans Endpoint (/api/plans)
  console.log('Test 8: Verify Public Active Plans Endpoint (GET /api/plans)...');
  const publicRes = await fetch(`${BASE_URL}/plans`);
  const publicData = await publicRes.json();
  if (!publicData.success || !Array.isArray(publicData.data)) {
    throw new Error(`Failed to fetch public plans: ${JSON.stringify(publicData)}`);
  }
  const hasInactiveCreatedPlan = publicData.data.some(p => p.id === createdPlanId);
  const hasInactiveDuplicatedPlan = publicData.data.some(p => p.id === duplicatedPlanId);
  if (hasInactiveCreatedPlan || hasInactiveDuplicatedPlan) {
    throw new Error(`Public plans returned inactive plans!`);
  }
  console.log(`  ✅ Passed: GET /api/plans returned ${publicData.data.length} active plans. Inactive plans correctly excluded.`);

  // Test 9: Security Guard - Institute Admin forbidden from Super Admin Plan management
  console.log('Test 9: Security Check - Institute Admin forbidden from /api/super-admin/plans...');
  const secRes = await fetch(`${BASE_URL}/super-admin/plans`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${instituteAdminToken}`,
    },
    body: JSON.stringify({ name: 'Hacker Plan', price: 0, duration: 1 }),
  });
  if (secRes.status !== 403) {
    throw new Error(`Security failed! Institute Admin received status ${secRes.status}, expected 403.`);
  }
  console.log('  ✅ Passed: Institute Admin blocked with 403 Forbidden.');

  // Test 10: Validation Rejections
  console.log('Test 10: Validation Rejections (Negative price / Negative limits / Invalid duration)...');
  const badRes1 = await fetch(`${BASE_URL}/super-admin/plans`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${superAdminToken}`,
    },
    body: JSON.stringify({
      name: 'Invalid Negative Price Plan',
      price: -500,
      duration: 1,
    }),
  });
  const badData1 = await badRes1.json();
  if (badRes1.status !== 400 || !badData1.message.includes('Price cannot be negative')) {
    throw new Error(`Validation failed for negative price: ${JSON.stringify(badData1)}`);
  }

  const badRes2 = await fetch(`${BASE_URL}/super-admin/plans`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${superAdminToken}`,
    },
    body: JSON.stringify({
      name: 'Invalid Negative Limit Plan',
      price: 1000,
      duration: 1,
      studentLimit: -20,
    }),
  });
  const badData2 = await badRes2.json();
  if (badRes2.status !== 400 || !badData2.message.includes('Student limit cannot be negative')) {
    throw new Error(`Validation failed for negative limit: ${JSON.stringify(badData2)}`);
  }
  console.log('  ✅ Passed: Invalid price and limit rejected with 400 and clear error messages.');

  // Test 11: Existing Step 1 Tenant Isolation Remains Intact
  console.log('Test 11: Existing Institute Tenant Queries still fully intact...');
  const classesRes = await fetch(`${BASE_URL}/academic/classes`, {
    headers: { Authorization: `Bearer ${instituteAdminToken}` },
  });
  const classesData = await classesRes.json();
  if (!classesData.success) {
    throw new Error(`Tenant query failed: ${JSON.stringify(classesData)}`);
  }
  console.log(`  ✅ Passed: Institute classes query succeeded (${classesData.data.length} classes returned).`);

  console.log('\n========================================================');
  console.log('🎉 ALL STEP 2 DYNAMIC PLAN MANAGEMENT TESTS PASSED 100%!');
  console.log('========================================================\n');
}

runStep2Tests().catch((err) => {
  console.error('\n❌ Test Suite Failed:', err);
  process.exit(1);
});
